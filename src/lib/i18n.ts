/** Languages whose script reads right-to-left. */
export const RTL_LANGUAGES = new Set(["العربية"]);

function fill(template: string, vars?: Record<string, string>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, key: string) => vars[key] ?? m);
}

/** Looks up `key` in `language`'s dictionary, falling back to English, and fills in `{placeholders}`. */
export function translate(language: string, key: TKey, vars?: Record<string, string>): string {
  const dict = DICTS[language] ?? EN;
  const template = dict[key] ?? EN[key];
  return fill(template, vars);
}

